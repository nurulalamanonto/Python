myVariableName = "Nurul"

"""When a space is required after first word
 just use capital letter of the next words first letter"""

#PascalCase:

MyVariableName = "Nurul"

"""Here first letter is capital and when a space is required
just use capital letter of the next words first letter"""

#snake_case:

